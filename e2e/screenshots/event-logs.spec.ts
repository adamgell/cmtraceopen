/**
 * Event Logs screenshot captures (`npm run screenshots -- -g event-logs`).
 *
 * Kept apart from capture.spec.ts so the two files can change independently. The `outPath` and
 * `dismissSplash` helpers below are copies of the ones there; consolidate them once both files
 * settle.
 *
 * Data path
 * ---------
 * The workspace is driven the way the source picker opens several files: `openEventLogSources`
 * calls `evtx_expand_sources`, then the store's `parseManifest` calls `evtx_parse_manifest`, then
 * the analysis pump calls the `evtx_*_analysis_*` commands. All of them are answered by
 * `window.__e2e_ipc_overrides__`:
 *
 * - `evtx_expand_sources` and `evtx_parse_manifest` are built by `buildSourceManifest()` and
 *   `buildParseResult()` (they need real .evtx files to come from the backend), following
 *   `build_source_manifest_for_selections` and `parse_evtx_manifest`. If one of them reports a
 *   mismatch, update that builder.
 * - the analysis-session and diagnosis commands REPLAY replies captured from the real engine
 *   (`event-log-engine-replies.json`, regenerated by `capture-event-log-replies.mjs`). Before
 *   anything runs, the hash of the engine input is compared with the one recorded at capture;
 *   each override then checks that the UI's request carries exactly the records the engine was
 *   given. Both fail with a regenerate message, so a stale capture cannot replay silently.
 *   Engine SOURCE drift cannot be seen from the spec; run
 *   `node e2e/fixtures/capture-event-log-replies.mjs --check` for that.
 *
 * The 127.0.0.1:1422 IPC bridge is blocked, so a running `npm run app:dev` cannot leak live host
 * replies into a capture: a command with no override gets the shim's static defaults.
 *
 * These captures are the baseline of the CURRENT Event Logs UI.
 */
import path from "node:path";
import { fileURLToPath } from "node:url";
import { test, expect } from "../fixtures";
import { assertNoHostPaths } from "../fixtures/host-path-guard";
import {
  buildParseResult,
  buildSourceManifest,
  buildSourceSelections,
  engineInputSha256,
  loadEngineReplies,
} from "../fixtures/event-log-data";
import { mergeDiagnosisCoverageGaps } from "../../src/workspaces/event-log/evtx-coverage";
import type { EvtxCoverageGap, EvtxParseResult } from "../../src/workspaces/event-log/types";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(HERE, "..", "..", "screenshots");
const outPath = (name: string) => path.join(OUT_DIR, name);

async function dismissSplash(
  page: import("@playwright/test").Page,
): Promise<void> {
  await page.waitForSelector("#splash", { state: "detached", timeout: 15_000 });
}

// Timestamps render in local time; pin the zone and locale so the PNGs do not depend on the host.
test.use({ timezoneId: "UTC", locale: "en-US" });

/** The one capture that shows the Insights coverage note (spec 8.13 item 2, Phase 4b #831). */
const COVERAGE_NOTE_CAPTURE = "event-logs coverage note";

/**
 * A live Security refusal as `absorb_scan` files it once #931 lands (src-tauri/src/event_log/
 * commands.rs): source = the channel, the reason from `describe_query_status` (live.rs).
 */
const LIVE_SECURITY_DENIED: EvtxCoverageGap = {
  source: "Security",
  kind: "accessDenied",
  reason: "the Event Log service refused the channel query (Windows error 5: Access is denied)",
};

/**
 * The coverage note capture's parse result: the fixture plus the live refusal, carried the way the
 * backend carries a gap (a structured gap, its "source: reason" message and one parse error).
 *
 * Caveats, by design of a replayed capture:
 * - a files load carrying a live-shape gap is a state the backend never produces; it is here so the
 *   capture shows the spec sentence "{channel} channel not read." next to the fixture's own file
 *   note ("Security.evtx not read.");
 * - the replayed diagnosis was captured without this gap, so the coverage disclosure still counts
 *   the fixture's gaps only.
 */
function withLiveSecurityRefusal(base: EvtxParseResult): EvtxParseResult {
  return {
    ...base,
    parseErrors: base.parseErrors + 1,
    errorMessages: [
      `${LIVE_SECURITY_DENIED.source}: ${LIVE_SECURITY_DENIED.reason}`,
      ...base.errorMessages,
    ],
    coverageGaps: [LIVE_SECURITY_DENIED, ...(base.coverageGaps ?? [])],
  };
}

test.describe("event-logs screenshots", () => {
  let timelineGridName: string;

  test.beforeEach(async ({ page }, testInfo) => {
    const fixtureParseResult = buildParseResult();
    const fixtureReplies = loadEngineReplies();
    if (engineInputSha256(fixtureParseResult) !== fixtureReplies.provenance.inputSha256) {
      throw new Error(
        "[event-logs fixture] the dataset changed since the engine replies were captured. " +
          "Regenerate with `node e2e/fixtures/capture-event-log-replies.mjs`.",
      );
    }
    // Every capture but the coverage note one is served the fixture exactly as before.
    const noteCapture = testInfo.title === COVERAGE_NOTE_CAPTURE;
    const parseResult = noteCapture
      ? withLiveSecurityRefusal(fixtureParseResult)
      : fixtureParseResult;
    // The diagnose check stays strict: for the note capture it expects exactly the gaps the UI
    // derives from that parse result. The store's legacy strings are the gaps' own "source: reason"
    // messages, which the merge drops as duplicates, so the error messages stand in for them.
    const replies = noteCapture
      ? {
          ...fixtureReplies,
          diagnoseCoverageGaps: mergeDiagnosisCoverageGaps(
            parseResult.coverageGaps ?? [],
            buildSourceManifest().coverage,
            parseResult.errorMessages,
            [],
          ),
        }
      : fixtureReplies;
    // The shim answers platformSupported: false, which hides the note; only this capture elevates.
    const elevation = noteCapture ? { platformSupported: true, isElevated: false } : null;
    timelineGridName = `Event log timeline - ${parseResult.records.length} records`;

    // Same guard as e2e/fixtures/index.ts: nothing here may talk to a running backend.
    await page.route("http://127.0.0.1:1422/**", (route) =>
      route.abort("connectionrefused"),
    );

    await page.addInitScript(
      ({ parseResult, replies, selections, manifest, elevation }) => {
        const overrides = window.__e2e_ipc_overrides__;
        if (elevation) overrides["get_app_elevation_state"] = () => elevation;
        const same = (a: unknown, b: unknown): boolean =>
          JSON.stringify(a) === JSON.stringify(b);
        const stale = (command: string, detail: string): Error =>
          new Error(
            `[event-logs fixture] ${command}: ${detail}. ` +
              "Regenerate with `node e2e/fixtures/capture-event-log-replies.mjs`.",
          );
        const requireSession = (command: string, args: { sessionId: string }) => {
          if (args.sessionId !== replies.sessionId) {
            throw stale(command, `unexpected session id ${args.sessionId}`);
          }
        };

        const mismatch = (command: string, detail: string): Error =>
          new Error(
            `[event-logs fixture] ${command}: ${detail}. ` +
              "Update buildSourceManifest/buildParseResult in e2e/fixtures/event-log-data.ts.",
          );

        let appendCalls = 0;
        overrides["evtx_expand_sources"] = (args: { sources: unknown[] }) => {
          if (!same(args.sources, selections)) {
            throw mismatch("evtx_expand_sources", "requested sources differ from the fixture's");
          }
          return manifest;
        };
        overrides["evtx_parse_manifest"] = (args: { manifest: unknown }) => {
          if (!same(args.manifest, manifest)) {
            throw mismatch("evtx_parse_manifest", "manifest differs from the one expanded");
          }
          return parseResult;
        };
        overrides["evtx_create_analysis_session"] = () => {
          appendCalls = 0;
          return replies.create;
        };
        overrides["evtx_append_analysis_chunk"] = (args: {
          sessionId: string;
          records: { record: unknown; originalSerializedBytes: unknown }[];
          entries: unknown[];
        }) => {
          requireSession("evtx_append_analysis_chunk", args);
          const expected = replies.appendChunkRecordCounts[appendCalls];
          if (args.records.length !== expected || args.entries.length !== 0) {
            throw stale(
              "evtx_append_analysis_chunk",
              `chunk ${appendCalls} carried ${args.records.length} records and ` +
                `${args.entries.length} entries, the capture saw ${expected} and 0`,
            );
          }
          // The engine was given the records unprojected; any UI-side projection or reshaping
          // would make the captured replies describe different input.
          const start = replies.appendChunkRecordCounts
            .slice(0, appendCalls)
            .reduce((total, count) => total + count, 0);
          args.records.forEach((input, index) => {
            const wanted = { record: parseResult.records[start + index], originalSerializedBytes: null };
            if (!same(input, wanted)) {
              throw stale(
                "evtx_append_analysis_chunk",
                `record ${start + index} differs from the one the engine was given`,
              );
            }
          });
          return replies.append[appendCalls++];
        };
        overrides["evtx_finalize_analysis_session"] = (args: { sessionId: string }) => {
          requireSession("evtx_finalize_analysis_session", args);
          return replies.finalize;
        };
        overrides["evtx_query_analysis_timeline"] = (args: {
          sessionId: string;
          offset: number;
          limit: number;
        }) => {
          requireSession("evtx_query_analysis_timeline", args);
          const captured = replies.timelinePages.find(
            (entry) => entry.offset === args.offset && entry.limit === args.limit,
          );
          if (!captured) {
            throw stale(
              "evtx_query_analysis_timeline",
              `no captured page for offset ${args.offset}, limit ${args.limit}`,
            );
          }
          return captured.page;
        };
        overrides["evtx_diagnose_analysis_session"] = (args: {
          sessionId: string;
          coverageGaps: unknown[];
        }) => {
          requireSession("evtx_diagnose_analysis_session", args);
          if (!same(args.coverageGaps, replies.diagnoseCoverageGaps)) {
            throw stale(
              "evtx_diagnose_analysis_session",
              "coverage gaps differ from the ones the engine was given",
            );
          }
          return replies.diagnosis;
        };
        overrides["evtx_close_analysis_session"] = () => null;
        // No saved markers for the fictional files.
        overrides["load_markers"] = () => null;
      },
      {
        parseResult,
        replies,
        selections: buildSourceSelections(),
        manifest: buildSourceManifest(),
        elevation,
      },
    );

    await page.goto("/");
    await dismissSplash(page);

    await page.evaluate(async (selections) => {
      const { useUiStore } = await import("/src/stores/ui-store.ts");
      const { openEventLogSources } = await import(
        "/src/workspaces/event-log/open-event-log-source.ts"
      );
      useUiStore.getState().setActiveWorkspace("event-log");
      await openEventLogSources(selections);
    }, buildSourceSelections());

    // A guard failure above surfaces in the UI as the diagnosis-error alert. Report its text
    // instead of letting the waits below time out blind.
    const alert = page.getByRole("alert");
    await expect(
      page.getByLabel("Operational diagnosis").or(alert).first(),
    ).toBeVisible({ timeout: 15_000 });
    if ((await alert.count()) > 0) {
      throw new Error(
        `Event Logs reported an error instead of the diagnosis: ${await alert.first().innerText()}`,
      );
    }

    // The grid, the diagnosis card and a loaded unified-timeline row all depend on the full
    // parse and analysis round trip, so together they mean the workspace has settled.
    await expect(page.getByRole("grid", { name: timelineGridName })).toBeVisible({
      timeout: 15_000,
    });
    await expect(page.getByLabel("Operational diagnosis")).toBeVisible({
      timeout: 15_000,
    });
    await expect(page.getByText("Loading timeline row")).toHaveCount(0);

    // Newest first, through the filter bar's own sort control, so the table opens on the Warning
    // rows instead of the early-morning run of Information rows. The first Error is row 39.
    await page
      .getByRole("button", { name: "Change sort direction to descending" })
      .click();
    await expect(
      page.getByRole("button", { name: "Change sort direction to ascending" }),
    ).toBeVisible();
  });

  test("event-logs table", async ({ page }) => {
    await expect(page.getByRole("region", { name: "Event log details" })).toHaveCount(0);
    await assertNoHostPaths(page);
    await page.screenshot({
      path: outPath("event-logs-table.png"),
      animations: "disabled",
    });
  });

  test("event-logs selected record", async ({ page }) => {
    // Select a record that IS finding evidence, so the Details callout shows: the DeviceManagement
    // 404 at record 89131, the first piece of evidence of the top finding. The engine's evidence is
    // the redacted display projection (machine as a [host:...] token, source as the file path), and
    // the callout matches on event ID, provider, channel and record ID, so this record matches
    // uniquely. A real row click drives it into Details: newest first, this record is row 1026 of
    // 1331, below the fold of a virtualized list, so scroll it into the rendered window first (the
    // way the Phase 2 capture did), then click it.
    const grid = page.getByRole("grid", { name: timelineGridName });
    await grid.evaluate((el) => {
      // Rows are not a fixed height (the level badge column varies), so scale by the list's own
      // height: a few rows above row 1026 of 1331.
      el.scrollTop = Math.floor((el.scrollHeight * 1022) / 1331);
    });
    const row = grid
      .getByRole("row")
      .filter({ hasText: "15:43:23" })
      .filter({ hasText: "MDM Configurati" })
      .first();
    await expect(row).toBeVisible();
    await row.click();
    const detail = page.getByRole("region", { name: "Event log details" });
    await expect(detail).toContainText("Command failure status");
    await expect(detail.getByRole("button", { name: /Part of finding/ })).toBeVisible();
    await assertNoHostPaths(page);
    await page.screenshot({
      path: outPath("event-logs-selected.png"),
      animations: "disabled",
    });
  });

  test("event-logs insights lower cards", async ({ page }) => {
    // The finding cards fill the top of the rail; scroll the panel to its end so the coverage
    // disclosure, level mix and top event IDs are reviewable. The correlation summary card does
    // not appear here: this fixture yields no correlation edges, so it waits for Phase 10's
    // fixture edges (#839).
    const panel = page.locator("#evtx-rail-panel-insights");
    await expect(panel).toBeVisible();
    await panel.evaluate((el) => {
      el.scrollTop = el.scrollHeight;
    });
    const rail = await page.locator('[data-evtx-region="rail"]').boundingBox();
    // The rail is 340 px wide at its default (spec 5.2).
    expect(Math.round(rail?.width ?? 0)).toBe(340);
    // And the channel pane is 250 px including its 1 px border (spec 5.2).
    // Measure the pane itself (the wrapper's child), not the wrapper around it.
    const channels = await page.locator('[data-evtx-region="channels"] > *').first().boundingBox();
    expect(Math.round(channels?.width ?? 0)).toBe(250);
    await expect(page.getByRole("region", { name: "Level mix" })).toBeVisible();
    await assertNoHostPaths(page);
    await page.screenshot({
      path: outPath("event-logs-insights.png"),
      animations: "disabled",
    });
  });

  test(COVERAGE_NOTE_CAPTURE, async ({ page }) => {
    // The rail on its Insights tab, so the note shows and the grid banner does not. Two notes: the
    // injected live refusal (the spec sentence) and the fixture's unreadable Security.evtx.
    const note = page.getByText("Security channel not read. Findings may be incomplete.");
    await expect(note).toBeVisible();
    await expect(
      page.getByText("Security.evtx not read. Findings may be incomplete."),
    ).toBeVisible();
    await expect(
      page.getByRole("button", { name: "Elevate to read Security", exact: true }),
    ).toBeVisible();
    await expect(page.locator("[data-coverage-banner]")).toHaveCount(0);
    await note.scrollIntoViewIfNeeded();
    await assertNoHostPaths(page);
    await page.screenshot({
      path: outPath("event-logs-coverage-note.png"),
      animations: "disabled",
    });
  });
});
