/**
 * Event Logs screenshot captures (`npm run screenshots -- -g event-logs`).
 *
 * Kept apart from capture.spec.ts so the two files can change independently. The `outPath` and
 * `dismissSplash` helpers below are copies of the ones there; consolidate them once both files
 * settle.
 *
 * Data path
 * ---------
 * The workspace is driven the way the source picker opens several files: `openEventLogSources`
 * calls `evtx_expand_sources`, then the store's `parseManifest` calls `evtx_parse_manifest`, then
 * the analysis pump calls the `evtx_*_analysis_*` commands. All of them are answered by
 * `window.__e2e_ipc_overrides__`:
 *
 * - `evtx_expand_sources` and `evtx_parse_manifest` are built by `buildSourceManifest()` and
 *   `buildParseResult()` (they need real .evtx files to come from the backend), following
 *   `build_source_manifest_for_selections` and `parse_evtx_manifest`. If one of them reports a
 *   mismatch, update that builder.
 * - the analysis-session and diagnosis commands REPLAY replies captured from the real engine
 *   (`event-log-engine-replies.json`, regenerated by `capture-event-log-replies.mjs`). Before
 *   anything runs, the hash of the engine input is compared with the one recorded at capture;
 *   each override then checks that the UI's request carries exactly the records the engine was
 *   given. Both fail with a regenerate message, so a stale capture cannot replay silently.
 *   Engine SOURCE drift cannot be seen from the spec; run
 *   `node e2e/fixtures/capture-event-log-replies.mjs --check` for that.
 *
 * The 127.0.0.1:1422 IPC bridge is blocked, so a running `npm run app:dev` cannot leak live host
 * replies into a capture: a command with no override gets the shim's static defaults.
 *
 * These captures are the baseline of the CURRENT Event Logs UI.
 */
import path from "node:path";
import { fileURLToPath } from "node:url";
import { test, expect } from "../fixtures";
import { assertNoHostPaths } from "../fixtures/host-path-guard";
import {
  buildParseResult,
  buildSourceManifest,
  buildSourceSelections,
  engineInputSha256,
  loadEngineReplies,
} from "../fixtures/event-log-data";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(HERE, "..", "..", "screenshots");
const outPath = (name: string) => path.join(OUT_DIR, name);

async function dismissSplash(
  page: import("@playwright/test").Page,
): Promise<void> {
  await page.waitForSelector("#splash", { state: "detached", timeout: 15_000 });
}

// Timestamps render in local time; pin the zone and locale so the PNGs do not depend on the host.
test.use({ timezoneId: "UTC", locale: "en-US" });

test.describe("event-logs screenshots", () => {
  let timelineGridName: string;

  test.beforeEach(async ({ page }) => {
    const parseResult = buildParseResult();
    const replies = loadEngineReplies();
    if (engineInputSha256(parseResult) !== replies.provenance.inputSha256) {
      throw new Error(
        "[event-logs fixture] the dataset changed since the engine replies were captured. " +
          "Regenerate with `node e2e/fixtures/capture-event-log-replies.mjs`.",
      );
    }
    timelineGridName = `Event log timeline - ${parseResult.records.length} records`;

    // Same guard as e2e/fixtures/index.ts: nothing here may talk to a running backend.
    await page.route("http://127.0.0.1:1422/**", (route) =>
      route.abort("connectionrefused"),
    );

    await page.addInitScript(
      ({ parseResult, replies, selections, manifest }) => {
        const overrides = window.__e2e_ipc_overrides__;
        const same = (a: unknown, b: unknown): boolean =>
          JSON.stringify(a) === JSON.stringify(b);
        const stale = (command: string, detail: string): Error =>
          new Error(
            `[event-logs fixture] ${command}: ${detail}. ` +
              "Regenerate with `node e2e/fixtures/capture-event-log-replies.mjs`.",
          );
        const requireSession = (command: string, args: { sessionId: string }) => {
          if (args.sessionId !== replies.sessionId) {
            throw stale(command, `unexpected session id ${args.sessionId}`);
          }
        };

        const mismatch = (command: string, detail: string): Error =>
          new Error(
            `[event-logs fixture] ${command}: ${detail}. ` +
              "Update buildSourceManifest/buildParseResult in e2e/fixtures/event-log-data.ts.",
          );

        let appendCalls = 0;
        overrides["evtx_expand_sources"] = (args: { sources: unknown[] }) => {
          if (!same(args.sources, selections)) {
            throw mismatch("evtx_expand_sources", "requested sources differ from the fixture's");
          }
          return manifest;
        };
        overrides["evtx_parse_manifest"] = (args: { manifest: unknown }) => {
          if (!same(args.manifest, manifest)) {
            throw mismatch("evtx_parse_manifest", "manifest differs from the one expanded");
          }
          return parseResult;
        };
        overrides["evtx_create_analysis_session"] = () => {
          appendCalls = 0;
          return replies.create;
        };
        overrides["evtx_append_analysis_chunk"] = (args: {
          sessionId: string;
          records: { record: unknown; originalSerializedBytes: unknown }[];
          entries: unknown[];
        }) => {
          requireSession("evtx_append_analysis_chunk", args);
          const expected = replies.appendChunkRecordCounts[appendCalls];
          if (args.records.length !== expected || args.entries.length !== 0) {
            throw stale(
              "evtx_append_analysis_chunk",
              `chunk ${appendCalls} carried ${args.records.length} records and ` +
                `${args.entries.length} entries, the capture saw ${expected} and 0`,
            );
          }
          // The engine was given the records unprojected; any UI-side projection or reshaping
          // would make the captured replies describe different input.
          const start = replies.appendChunkRecordCounts
            .slice(0, appendCalls)
            .reduce((total, count) => total + count, 0);
          args.records.forEach((input, index) => {
            const wanted = { record: parseResult.records[start + index], originalSerializedBytes: null };
            if (!same(input, wanted)) {
              throw stale(
                "evtx_append_analysis_chunk",
                `record ${start + index} differs from the one the engine was given`,
              );
            }
          });
          return replies.append[appendCalls++];
        };
        overrides["evtx_finalize_analysis_session"] = (args: { sessionId: string }) => {
          requireSession("evtx_finalize_analysis_session", args);
          return replies.finalize;
        };
        overrides["evtx_query_analysis_timeline"] = (args: {
          sessionId: string;
          offset: number;
          limit: number;
        }) => {
          requireSession("evtx_query_analysis_timeline", args);
          const captured = replies.timelinePages.find(
            (entry) => entry.offset === args.offset && entry.limit === args.limit,
          );
          if (!captured) {
            throw stale(
              "evtx_query_analysis_timeline",
              `no captured page for offset ${args.offset}, limit ${args.limit}`,
            );
          }
          return captured.page;
        };
        overrides["evtx_diagnose_analysis_session"] = (args: {
          sessionId: string;
          coverageGaps: unknown[];
        }) => {
          requireSession("evtx_diagnose_analysis_session", args);
          if (!same(args.coverageGaps, replies.diagnoseCoverageGaps)) {
            throw stale(
              "evtx_diagnose_analysis_session",
              "coverage gaps differ from the ones the engine was given",
            );
          }
          return replies.diagnosis;
        };
        overrides["evtx_close_analysis_session"] = () => null;
        // No saved markers for the fictional files.
        overrides["load_markers"] = () => null;
      },
      {
        parseResult,
        replies,
        selections: buildSourceSelections(),
        manifest: buildSourceManifest(),
      },
    );

    await page.goto("/");
    await dismissSplash(page);

    await page.evaluate(async (selections) => {
      const { useUiStore } = await import("/src/stores/ui-store.ts");
      const { openEventLogSources } = await import(
        "/src/workspaces/event-log/open-event-log-source.ts"
      );
      useUiStore.getState().setActiveWorkspace("event-log");
      await openEventLogSources(selections);
    }, buildSourceSelections());

    // A guard failure above surfaces in the UI as the diagnosis-error alert. Report its text
    // instead of letting the waits below time out blind.
    const alert = page.getByRole("alert");
    await expect(
      page.getByLabel("Operational diagnosis").or(alert).first(),
    ).toBeVisible({ timeout: 15_000 });
    if ((await alert.count()) > 0) {
      throw new Error(
        `Event Logs reported an error instead of the diagnosis: ${await alert.first().innerText()}`,
      );
    }

    // The grid, the diagnosis card and a loaded unified-timeline row all depend on the full
    // parse and analysis round trip, so together they mean the workspace has settled.
    await expect(page.getByRole("grid", { name: timelineGridName })).toBeVisible({
      timeout: 15_000,
    });
    await expect(page.getByLabel("Operational diagnosis")).toBeVisible({
      timeout: 15_000,
    });
    await expect(page.getByText("Loading timeline row")).toHaveCount(0);

    // Newest first, through the filter bar's own sort control, so the table opens on the Warning
    // rows instead of the early-morning run of Information rows. The first Error is row 39.
    await page
      .getByRole("button", { name: "Change sort direction to descending" })
      .click();
    await expect(
      page.getByRole("button", { name: "Change sort direction to ascending" }),
    ).toBeVisible();
  });

  test("event-logs table", async ({ page }) => {
    await expect(page.getByRole("region", { name: "Event log details" })).toHaveCount(0);
    await assertNoHostPaths(page);
    await page.screenshot({
      path: outPath("event-logs-table.png"),
      animations: "disabled",
    });
  });

  test("event-logs selected record", async ({ page }) => {
    const grid = page.getByRole("grid", { name: timelineGridName });
    // Newest first, the first Error record (MsiInstaller 11708) is below the fold of a virtualized
    // list, so scroll it into the rendered window before clicking. Its index comes from the
    // fixture and the row height from the page, so this does not depend on either row height or
    // where the record falls.
    const newestFirst = [...buildParseResult().records].sort(
      (a, b) => b.timestampEpoch - a.timestampEpoch,
    );
    const targetIndex = newestFirst.findIndex((record) =>
      record.message.includes("Installation failed."),
    );
    expect(targetIndex, "the fixture holds the Installation failed. record").toBeGreaterThanOrEqual(0);
    const rowHeight = await grid
      .getByRole("row")
      .first()
      .evaluate((el) => el.getBoundingClientRect().height);
    await grid.evaluate((el, top) => {
      el.scrollTop = top;
    }, targetIndex * rowHeight);
    const row = grid
      .getByRole("row")
      .filter({ hasText: "Installation failed." })
      .first();
    await row.scrollIntoViewIfNeeded();
    await row.click();
    await expect(
      page.getByRole("region", { name: "Event log details" }),
    ).toContainText("Installation failed.");

    // At 1440x900 the 320 px unified-timeline pane and the 300 px Details pane leave the grid
    // about 0 px once a record is selected, so the capture showed no table. Drag the Details
    // pane's handle down to its 100 px minimum. That handle is a plain mouse handle (it has no
    // keyboard separator role), so the drag is the way to resize it.
    // The dock's handle (a hidden `separator`) also carries a row-resize cursor, so take the visible
    // one that is not a separator.
    const handle = page.locator('div[style*="row-resize"]:not([role="separator"]):visible');
    await expect(handle).toHaveCount(1);
    const box = (await handle.boundingBox())!;
    const x = box.x + box.width / 2;
    await page.mouse.move(x, box.y + box.height / 2);
    await page.mouse.down();
    await page.mouse.move(x, box.y + 300, { steps: 8 });
    await page.mouse.up();

    // Put the selected row, with a tinted neighbour above it, in the grid, and require that the
    // capture really shows the table: its header, and the selected row inside the viewport.
    await grid.evaluate((el, top) => {
      el.scrollTop = top;
    }, Math.max(0, targetIndex - 1) * rowHeight);
    const selectedRow = grid.locator('[role="row"][aria-selected="true"]');
    await expect(selectedRow).toHaveCount(1);
    await expect(selectedRow).toContainText("Installation failed.");
    await expect(selectedRow).toBeInViewport({ ratio: 1 });
    await expect(page.locator("[data-evtx-table-header]")).toBeInViewport({ ratio: 1 });
    await assertNoHostPaths(page);
    await page.screenshot({
      path: outPath("event-logs-selected.png"),
      animations: "disabled",
    });
  });

  // The table's states in one frame: the Error and Warning tints, plain rows, the selected row
  // (Q-1) and the quick-filter highlight, so spec 8.7 can be reviewed from one image. The
  // quick filter "ion" keeps rows of every level (resolution, Installation, Operational,
  // Application, Protection) and highlights it in the channel and message cells. The Error row is
  // the first "Installation failed." and the row after it is selected, so the Error tint stays
  // visible beside the selection. No Critical row falls near it, so the frame shows Error.
  test("event-logs table states", async ({ page }) => {
    // Tall enough for the unified-timeline pane, the Details pane and about twenty grid rows.
    await page.setViewportSize({ width: 1440, height: 1500 });
    await page.getByPlaceholder("Quick filter...").fill("ion");
    const grid = page.getByRole("grid", { name: /^Event log timeline - \d+ records$/ });
    await expect(grid).not.toHaveAttribute("aria-label", timelineGridName);

    const settle = () =>
      page.evaluate(
        () =>
          new Promise<void>((resolve) =>
            requestAnimationFrame(() => requestAnimationFrame(() => resolve())),
          ),
      );
    const rowHeight = await grid
      .getByRole("row")
      .first()
      .evaluate((el) => el.getBoundingClientRect().height);
    const scrollTo = async (top: number) => {
      await grid.evaluate((el, y) => {
        el.scrollTop = y;
      }, top);
      await settle();
    };

    // Page down until the Error row is rendered; its data-index is then its position in the
    // filtered list, whatever the filter kept.
    const errorRow = grid.getByRole("row").filter({ hasText: "Installation failed." }).first();
    const scrollHeight = await grid.evaluate((el) => el.scrollHeight);
    let found = false;
    for (let top = 0; top <= scrollHeight && !found; top += 10 * rowHeight) {
      await scrollTo(top);
      found = (await errorRow.count()) > 0;
    }
    expect(found, "the filtered list holds the Installation failed. row").toBe(true);
    const errorIndex = Number(await errorRow.getAttribute("data-index"));

    await grid.locator(`[role="row"][data-index="${errorIndex + 1}"]`).click();
    await expect(page.getByRole("region", { name: "Event log details" })).toBeVisible();
    await scrollTo(Math.max(0, errorIndex - 5) * rowHeight);

    // The frame must hold every state it is meant to show, fully inside the grid.
    const rows = await grid.evaluate((el) => {
      const box = el.getBoundingClientRect();
      return Array.from(el.querySelectorAll<HTMLElement>('[role="row"]'))
        .filter((row) => {
          const r = row.getBoundingClientRect();
          return r.top >= box.top && r.bottom <= box.bottom;
        })
        .map((row) => ({
          level: row.querySelector("[data-evtx-level-cell]")?.getAttribute("aria-label") ?? "",
          selected: row.getAttribute("aria-selected") === "true",
          marks: row.querySelectorAll("mark").length,
        }));
    });
    const unselected = (level: string) =>
      rows.some((row) => !row.selected && row.level === level);
    expect(unselected("Level: Error"), JSON.stringify(rows)).toBe(true);
    expect(unselected("Level: Warning"), JSON.stringify(rows)).toBe(true);
    expect(unselected("Level: Information"), JSON.stringify(rows)).toBe(true);
    expect(rows.filter((row) => row.selected), JSON.stringify(rows)).toHaveLength(1);
    expect(rows.some((row) => row.marks > 0), JSON.stringify(rows)).toBe(true);

    await assertNoHostPaths(page);
    // The header and the grid are siblings inside the table's wrapper.
    const table = page.locator("[data-evtx-table-header]").locator("xpath=..");
    await table.screenshot({
      path: outPath("event-logs-table-states.png"),
      animations: "disabled",
    });
  });

  // The Grouped view (spec 8.8, #844) with its first group, the most severe in sort order,
  // expanded: the summary rows, the trend sparklines, the group's newest events and its Show all
  // action. The fixture has no correlation edges, so no event carries the Linked badge.
  test("event-logs grouped view", async ({ page }) => {
    await page.getByRole("tab", { name: "Grouped" }).click();
    const grouped = page.getByRole("table", { name: /^Grouped events, [\d,]+ groups by Event ID$/ });
    await expect(grouped).toBeVisible();
    // The fixture is a file set, so the time window is All and the trend spans the loaded events.
    await expect(grouped.getByRole("columnheader", { name: "All loaded trend" })).toBeVisible();

    const first = grouped.getByRole("button", { name: /^Event ID \d+, / }).first();
    await first.click();
    await expect(first).toHaveAttribute("aria-expanded", "true");
    await expect(grouped.getByRole("button", { name: /^Show all [\d,]+ in table$/ })).toBeVisible();

    await assertNoHostPaths(page);
    await page.screenshot({
      path: outPath("event-logs-grouped.png"),
      animations: "disabled",
    });
  });
});
